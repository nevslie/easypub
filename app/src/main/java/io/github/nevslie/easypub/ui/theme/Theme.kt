@Composable
fun AppTheme.isDark(): Boolean = when (this) {
    AppTheme.SYSTEM -> isSystemInDarkTheme()
    AppTheme.LIGHT -> false
    AppTheme.DARK -> true
}

@Composable
fun EasyPubTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    CompositionLocalProvider(LocalDarkTheme provides darkTheme) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColors else LightColors,
            typography = EasyPubTypography,
            shapes = EasyPubShapes,
            content = content,
        )
    }
}

/** Ob gerade das dunkle Farbschema aktiv ist. */
val LocalDarkTheme = staticCompositionLocalOf { false }

/** Feste Pastellfarbe für eine ID, z. B. für Library-Kacheln. */
@Composable
@ReadOnlyComposable
fun accentColorFor(id: Long): Color {
    val accent = AccentColors[Math.floorMod(id, AccentColors.size.toLong()).toInt()]
    return if (LocalDarkTheme.current) accent.dark else accent.light
}
